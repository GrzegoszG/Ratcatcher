def sfx():
    lines = []
    for i in range(64):
        if i in SFX:
            notes, speed = SFX[i]
            lines.append(sfx_line(notes, speed))
        else:
            lines.append(sfx_line([], 16))
    return "\n".join(lines)


def music():
    lines = ["03 14154344"] + ["00 41424344"] * 63
