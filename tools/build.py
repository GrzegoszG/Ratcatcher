def gfx():
    px = [["0"] * 128 for _ in range(128)]
    for n, rows in S.items():
        assert len(rows) == 8 and all(len(r) == 8 for r in rows), n
        sx, sy = n % 16 * 8, n // 16 * 8
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                px[sy + y][sx + x] = c
    return "\n".join("".join(r) for r in px)


def gff():
    f = [0] * 256
    for k, v in FLAGS.items():
        f[k] = v
    h = "".join("%02x" % v for v in f)
    return h[:256] + "\n" + h[256:]


# ---------------------------------------------------------------- dzwieki
# nuta: (wysokosc 0-63, fala 0-7, glosnosc 0-7, efekt 0-7)
def sfx_line(notes, speed, loop=(0, 0)):
    notes = list(notes) + [(0, 0, 0, 0)] * (32 - len(notes))
    s = "00%02x%02x%02x" % (speed, loop[0], loop[1])
    for p, w, v, e in notes[:32]:
        s += "%02x%x%x%x" % (p, w, v, e)
    return s


